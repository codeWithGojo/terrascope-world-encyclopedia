#!/usr/bin/env node

import {writeFile} from "node:fs/promises";
import worldCountries from "world-countries";

const endpoint = "https://api.worldbank.org/v2/country/all/indicator/SP.POP.TOTL?format=json&mrnev=1&per_page=400";
const sovereignExtras = new Set(["VA", "PS"]);
const sovereignCountries = worldCountries.filter(
  (country) => country.unMember || sovereignExtras.has(country.cca2),
);
const cca2ByCca3 = new Map(
  sovereignCountries.map((country) => [country.cca3, country.cca2]),
);

const response = await fetch(endpoint);
if (!response.ok) {
  throw new Error(`World Bank population request failed: ${response.status}`);
}

const payload = await response.json();
const [metadata, observations] = payload;
const records = new Map();

for (const observation of observations) {
  const code = cca2ByCca3.get(observation.countryiso3code);
  if (!code || typeof observation.value !== "number") continue;
  records.set(code, {
    value: Math.round(observation.value),
    year: Number(observation.date),
    source: "World Bank",
  });
}

// The World Bank series does not publish Vatican City. The Governorate's
// official statistical page reports 882 residents at 31 December 2024.
records.set("VA", {
  value: 882,
  year: 2024,
  source: "Vatican City State",
});

const missing = sovereignCountries.filter((country) => !records.has(country.cca2));
if (missing.length) {
  throw new Error(`Missing population records: ${missing.map((country) => country.cca2).join(", ")}`);
}

const entries = [...records.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, record]) => `  ${JSON.stringify(code)}: ${JSON.stringify(record)},`)
  .join("\n");

const output = `// Generated by scripts/refresh-population.mjs. Do not hand-edit.\n` +
  `// World Bank indicator SP.POP.TOTL; Vatican City uses its official resident count.\n\n` +
  `export type PopulationRecord = {value:number;year:number;source:"World Bank"|"Vatican City State"};\n\n` +
  `export const populationDataset = {\n` +
  `  indicator: "SP.POP.TOTL",\n` +
  `  worldBankLastUpdated: ${JSON.stringify(metadata.lastupdated)},\n` +
  `  refreshedAt: ${JSON.stringify(new Date().toISOString().slice(0, 10))},\n` +
  `  worldBankUrl: ${JSON.stringify(endpoint)},\n` +
  `  vaticanUrl: "https://www.vaticanstate.va/en/state-and-government/general-informations/population.html",\n` +
  `} as const;\n\n` +
  `export const populationByCode: Record<string,PopulationRecord> = {\n${entries}\n};\n`;

await writeFile(new URL("../app/population-data.ts", import.meta.url), output);
console.log(`Saved ${records.size} population records (${metadata.lastupdated}).`);
